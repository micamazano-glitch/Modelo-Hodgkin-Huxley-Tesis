import numpy as np
import matplotlib.pyplot as plt

# =====================================================
# MODELO COMPLETO DE HODGKIN-HUXLEY
# Comparacion de las constantes de tiempo m, h y n
# =====================================================

# Funciones auxiliares para evitar divisiones 0/0
def vtrap(x, y):
    z = x / y
    return np.where(
        np.abs(z) < 1e-6,
        y * (1 - z / 2 + z**2 / 12),
        x / np.expm1(z)
    )

# Tasas de transicion (V en mV)
# Convencion: potencial de reposo cercano a -65 mV

def alpha_m(V):
    return 0.1 * vtrap(-(V + 40), 10)

def beta_m(V):
    return 4.0 * np.exp(-(V + 65) / 18)

def alpha_h(V):
    return 0.07 * np.exp(-(V + 65) / 20)

def beta_h(V):
    return 1.0 / (1.0 + np.exp(-(V + 35) / 10))

def alpha_n(V):
    return 0.01 * vtrap(-(V + 55), 10)

def beta_n(V):
    return 0.125 * np.exp(-(V + 65) / 80)

# Constantes de tiempo, en milisegundos
def tau_m(V):
    return 1.0 / (alpha_m(V) + beta_m(V))

def tau_h(V):
    return 1.0 / (alpha_h(V) + beta_h(V))

def tau_n(V):
    return 1.0 / (alpha_n(V) + beta_n(V))

# Intervalo de potenciales
V = np.linspace(-100, 60, 1000)

tm = tau_m(V)
th = tau_h(V)
tn = tau_n(V)

# =====================================================
# GRAFICO 1: LAS TRES CONSTANTES DE TIEMPO
# =====================================================

plt.figure(figsize=(9, 5.5))

plt.plot(V, tm, label=r"$\tau_m(V)$", linewidth=2)
plt.plot(V, th, label=r"$\tau_h(V)$", linewidth=2)
plt.plot(V, tn, label=r"$\tau_n(V)$", linewidth=2)

plt.xlabel("Potencial de membrana V (mV)")
plt.ylabel("Constante de tiempo (ms)")
plt.title("Comparacion de escalas temporales")
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()

plt.savefig("constantes_tiempo_HH.png", dpi=300)
plt.show()

# =====================================================
# GRAFICO 2: RELACIONES ENTRE CONSTANTES DE TIEMPO
# =====================================================

plt.figure(figsize=(9, 5.5))

plt.plot(V, th / tm,
         label=r"$\tau_h/\tau_m$", linewidth=2)

plt.plot(V, tn / tm,
         label=r"$\tau_n/\tau_m$", linewidth=2)

plt.axhline(1, color="black", linestyle="--",
            label="Igualdad de escalas")

plt.xlabel("Potencial de membrana V (mV)")
plt.ylabel("Relacion de constantes de tiempo")
plt.title("Separacion de escalas temporales")
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()

plt.savefig("relaciones_tiempo_HH.png", dpi=300)
plt.show()

# =====================================================
# TABLA NUMERICA
# =====================================================

print("\nCOMPARACION DE CONSTANTES DE TIEMPO")
print("-" * 76)
print(f"{'V (mV)':>8} {'tau_m':>12} {'tau_h':>12} "
      f"{'tau_n':>12} {'tau_h/tau_m':>14} "
      f"{'tau_n/tau_m':>14}")
print("-" * 76)

for v in [-80, -65, -60, -40, -20, 0, 20, 40]:
    m = float(tau_m(v))
    h = float(tau_h(v))
    n = float(tau_n(v))

    print(f"{v:8.0f} {m:12.4f} {h:12.4f} "
          f"{n:12.4f} {h/m:14.2f} {n/m:14.2f}")

# Guardar tabla completa en CSV
datos = np.column_stack([
    V, tm, th, tn, th/tm, tn/tm
])

np.savetxt(
    "tabla_constantes_tiempo_HH.csv",
    datos,
    delimiter=",",
    header="V_mV,tau_m_ms,tau_h_ms,tau_n_ms,"
           "tau_h_sobre_tau_m,tau_n_sobre_tau_m",
    comments=""
)

print("\nArchivos generados correctamente.")