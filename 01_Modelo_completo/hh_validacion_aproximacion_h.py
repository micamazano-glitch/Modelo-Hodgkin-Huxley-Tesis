import numpy as np
import matplotlib.pyplot as plt


# Parametros clasicos de Hodgkin-Huxley
C_m = 1.0          # microF/cm^2
G_Na = 120.0       # mS/cm^2
G_K = 36.0         # mS/cm^2
G_L = 0.3          # mS/cm^2
E_Na = 50.0        # mV
E_K = -77.0        # mV
E_L = -54.4        # mV
I_app = 6.75       # microA/cm^2


def vtrap(x, y):
    """Evalua x/(exp(x/y)-1) de forma estable cerca de x=0."""
    if abs(x / y) < 1e-6:
        return y * (1.0 - x / (2.0 * y))
    return x / np.expm1(x / y)


def alpha_m(V):
    return 0.1 * vtrap(-(V + 40.0), 10.0)


def beta_m(V):
    return 4.0 * np.exp(-(V + 65.0) / 18.0)


def alpha_h(V):
    return 0.07 * np.exp(-(V + 65.0) / 20.0)


def beta_h(V):
    return 1.0 / (1.0 + np.exp(-(V + 35.0) / 10.0))


def alpha_n(V):
    return 0.01 * vtrap(-(V + 55.0), 10.0)


def beta_n(V):
    return 0.125 * np.exp(-(V + 65.0) / 80.0)


def estado_estacionario(alpha, beta, V):
    return alpha(V) / (alpha(V) + beta(V))


def modelo_hh(t, y):
    V, m, h, n = y

    I_Na = G_Na * m**3 * h * (V - E_Na)
    I_K = G_K * n**4 * (V - E_K)
    I_L = G_L * (V - E_L)

    dV = (I_app - I_Na - I_K - I_L) / C_m
    dm = alpha_m(V) * (1.0 - m) - beta_m(V) * m
    dh = alpha_h(V) * (1.0 - h) - beta_h(V) * h
    dn = alpha_n(V) * (1.0 - n) - beta_n(V) * n

    return [dV, dm, dh, dn]


# Metodo de Runge-Kutta de cuarto orden
def paso_rk4(f, t, y, dt):
    k1 = np.asarray(f(t, y))
    k2 = np.asarray(f(t + dt / 2.0, y + dt * k1 / 2.0))
    k3 = np.asarray(f(t + dt / 2.0, y + dt * k2 / 2.0))
    k4 = np.asarray(f(t + dt, y + dt * k3))

    return y + (dt / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)



# Corrientes que vamos a comparar
corrientes = [6.75, 6.76, 12.0]

# Misma condición inicial para las tres simulaciones
V_0 = -65.0
m_0 = estado_estacionario(alpha_m, beta_m, V_0)
h_0 = estado_estacionario(alpha_h, beta_h, V_0)
n_0 = estado_estacionario(alpha_n, beta_n, V_0)

t_0 = 0.0
t_final = 100.0
dt = 0.01
t = np.arange(t_0, t_final + dt, dt)

for corriente in corrientes:

    # Se actualiza la corriente utilizada por modelo_hh
    I_app = corriente

    solucion = np.zeros((len(t), 4))
    solucion[0] = [V_0, m_0, h_0, n_0]

    for i in range(len(t) - 1):
        solucion[i + 1] = paso_rk4(
            modelo_hh, t[i], solucion[i], dt
        )

    V = solucion[:, 0]
    m = solucion[:, 1]
    h = solucion[:, 2]
    n = solucion[:, 3]

    h_aprox = 0.89 - 1.1 * n
    error = h - h_aprox

    # Medidas cuantitativas del error
    error_maximo = np.max(np.abs(error))
    error_rms = np.sqrt(np.mean(error**2))

    print(f"\nI_app = {corriente:.2f} uA/cm^2")
    print(f"Error máximo = {error_maximo:.6f}")
    print(f"Error RMS    = {error_rms:.6f}")

    # Guardar resultados
    etiqueta = f"{corriente:.2f}".replace(".", "_")

    np.savetxt(
        f"soluciones_HH_I{etiqueta}.csv",
        np.column_stack(
            (t, V, m, h, n, h_aprox, error)
        ),
        delimiter=",",
        header="t_ms,V_mV,m,h,n,h_aproximada,error",
        comments=""
    )

    # Gráficas
    fig, ax = plt.subplots(
        4, 1, figsize=(5, 6), sharex=True
    )

    ax[0].plot(t, V, color="black", linewidth=1.2)
    ax[0].set_ylabel(r"$V(t)$ (mV)")
    ax[0].set_title(
        "Modelo completo de Hodgkin--Huxley, "
        + rf"$I_{{\mathrm{{app}}}}={corriente:.2f}$"
        + r" $\mu\mathrm{A}/\mathrm{cm}^2$"
    )

    ax[1].plot(t, n, color="tab:blue")
    ax[1].set_ylabel(r"$n(t)$")
    ax[1].set_ylim(0, 1)

    ax[2].plot(
        t, h, color="tab:red",
        label=r"$h(t)$"
    )
    ax[2].plot(
        t, h_aprox, color="tab:blue",
        linestyle="--",
        label=r"$0.89-1.1n(t)$"
    )
    ax[2].set_ylabel(r"$h(t)$")
    ax[2].set_ylim(0, 1)
    ax[2].legend()

    ax[3].plot(
        t, error, color="tab:purple"
    )
    ax[3].axhline(
        0, color="gray", linestyle="--"
    )
    ax[3].set_ylabel(r"$e(t)$")
    ax[3].set_xlabel(r"$t$ (ms)")

    for eje in ax:
        eje.grid(alpha=0.25)
        eje.set_xlim(t[0], t[-1])

    fig.tight_layout()
    fig.savefig(
        f"HH_I{etiqueta}_comparacion_error.png",
        dpi=300,
        bbox_inches="tight"
    )
    plt.show()