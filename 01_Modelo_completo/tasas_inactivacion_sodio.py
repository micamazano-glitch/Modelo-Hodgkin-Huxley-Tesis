import numpy as np
import matplotlib.pyplot as plt

# Rango de voltajes (en volts)
V = np.linspace(-100, 30, 500)  # desde -100 mV a +30 mV



# α y β para h
alpha_h =0.07*np.exp(-(V + 65)/20) #0.07 * np.exp(-0.5 * (V + 65))
beta_h =1/(1 + np.exp(-(V + 35)/10)) #1 / (1 + np.exp(-0.1 * (V + 35)))



# Graficar
plt.figure(figsize=(8, 5))



plt.plot(V , alpha_h, label=r'$\alpha_h$',linewidth=3)
plt.plot(V , beta_h, label=r'$\beta_h$',linewidth=3)
plt.title('Inactivación del sodio',fontsize=20)
plt.xlabel('VOLTAJE DE MEMBRANA (mV)',fontsize=16)
plt.ylabel('TASA (1/ms)',fontsize=16)
plt.ylim(0, 1)  # Establecer el rango del eje y
plt.legend(fontsize=16)
#plt.grid()

plt.tight_layout()
plt.show()