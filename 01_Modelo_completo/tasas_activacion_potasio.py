import numpy as np
import matplotlib.pyplot as plt

# Rango de voltajes (en volts)
V = np.linspace(-100, 30, 500)  # desde -100 mV a +30 mV



# α y β para n
alpha_n = (0.01 * (V + 55)) / (1 - np.exp(-(V + 55) * 0.10))
beta_n = 0.125 * np.exp(-(V + 65)* 0.0125)

# Graficar
plt.figure(figsize=(8, 5))



#plt.subplot(3, 1, 3)
plt.plot(V , alpha_n, label=r'$\alpha_n$',linewidth=3)
plt.plot(V , beta_n, label=r'$\beta_n$',linewidth=3)
plt.title('Activación del Potasio',fontsize=20)
plt.xlabel('VOLTAJE DE MEMBRANA (mV)',fontsize=16)
plt.ylabel('TASA (1/ms)',fontsize=16)
plt.ylim(0, 1)  # Establecer el rango del eje y
plt.legend(fontsize=16)
#plt.grid()

plt.tight_layout()
plt.show()