import numpy as np
import matplotlib.pyplot as plt

# Constantes del modelo
C_m = 1.0     # uF/cm²
g_Na = 120.0  # mS/cm²
g_K = 36.0    # mS/cm²
g_L = 0.3     # mS/cm²
E_Na = 50.0   # mV
E_K = -77.0   # mV
E_L = -54.387 # mV

# Corriente de entrada externa
def I_ext(t):
    return 6 if 0.1 <= t <= 100 else 0  # pulso entre 0.1 y 100 ms

# Funciones alfa y beta
def alpha_n(V): return 0.01*(V + 55)/(1 - np.exp(-(V + 55)/10))#parametros del abbott
def beta_n(V): return 0.125*np.exp(-(V + 65)/80)
def alpha_m(V): return 0.1*(V + 40)/(1 - np.exp(-(V + 40)/10))
def beta_m(V): return 4.0*np.exp(-(V + 65)/18)
def alpha_h(V): return 0.07*np.exp(-(V + 65)/20)
def beta_h(V): return 1/(1 + np.exp(-(V + 35)/10))

# Derivadas del sistema
def compute_derivatives(V, n, m, h, t):
    I = I_ext(t)
    I_Na = g_Na * m**3 * h * (V - E_Na)
    I_K = g_K * n**4 * (V - E_K)
    I_L = g_L * (V - E_L)
    dV = (I - I_Na - I_K - I_L) / C_m
    dn = alpha_n(V)*(1 - n) - beta_n(V)*n
    dm = alpha_m(V)*(1 - m) - beta_m(V)*m
    dh = alpha_h(V)*(1 - h) - beta_h(V)*h
    return dV, dn, dm, dh

# Condiciones iniciales
V = -61.6  # mV
n = alpha_n(V) / (alpha_n(V) + beta_n(V))
m = alpha_m(V) / (alpha_m(V) + beta_m(V))
h = alpha_h(V) / (alpha_h(V) + beta_h(V))

# Parámetros de simulación
T = 100     # ms
dt = 0.01  # paso de tiempo
N = int(T / dt)
times = np.linspace(0, T, N)
Vs = []

# Bucle de Euler
for i in range(N):
    Vs.append(V)
    dV, dn, dm, dh = compute_derivatives(V, n, m, h, times[i])
    V += dt * dV
    n += dt * dn
    m += dt * dm
    h += dt * dh

# Graficar
plt.plot(times, Vs, "g",linewidth=2)
plt.title("Modelo de Hodgkin-Huxley (Iapp=6)",fontsize=16)
plt.xlabel("Tiempo (ms)",fontsize=16)
plt.ylabel("Potencial de membrana (mV)",fontsize=16)
plt.ylim(-63, -60)  # Establecer el rango del eje y
plt.grid()
plt.show()