import numpy as np
import matplotlib.pyplot as plt

# Sistema de Van der Pol
def f(t, X, mu):
    x, y = X
    return np.array([y, -x - mu*(x**2 - 1)*y])

# Método Runge-Kutta de cuarto orden
def rk4(f, t0, X0, h, N, mu):
    t = t0
    X = np.array(X0, dtype=float)
    sol = [X.copy()]

    for i in range(N):
        k1 = f(t, X, mu)
        k2 = f(t + h/2, X + h*k1/2, mu)
        k3 = f(t + h/2, X + h*k2/2, mu)
        k4 = f(t + h, X + h*k3, mu)

        X = X + (h/6)*(k1 + 2*k2 + 2*k3 + k4)
        t += h
        sol.append(X.copy())

    return np.array(sol)

# Parámetros numéricos
h = 0.01
N = 6000

# Valores de mu
valores_mu = [1.5, 2, 3]

# Condiciones iniciales
initial_conditions = [
    (0.1, 0.1),
    (-0.1, -0.1),
    (2, 3),
    (-3, 2),
    (-3, -3),
    (2.5, -2.5)
]

colors = ['blue', 'green', 'orange',
          'purple', 'red', 'magenta']

# Generar una figura para cada valor de mu
for mu in valores_mu:

    plt.figure(figsize=(6, 4))

    for ic, c in zip(initial_conditions, colors):

        sol = rk4(f, 0, ic, h, N, mu)

        x = sol[:, 0]
        y = sol[:, 1]

        # Trayectoria
        plt.plot(x, y, color=c, label=f"CI={ic}")

        # Flechas de dirección
        step = 500
        for i in range(0, len(x)-1, step):
            plt.arrow(
                x[i], y[i],
                x[i+1]-x[i], y[i+1]-y[i],
                shape='full',
                head_width=0.15,
                length_includes_head=True,
                color=c
            )

        # Última parte de la trayectoria
        plt.plot(x[-1500:], y[-1500:],
                 color='black', linewidth=2)

    # Punto de equilibrio
    plt.plot(0, 0, marker='o',
             mfc='none', mec='black', ms=8)

    # Ejes coordenados
    plt.axhline(0)
    plt.axvline(0)

    plt.xlabel("x")
    plt.ylabel("y")
    plt.title(f"Retrato de fase - Van der Pol (μ = {mu})")

    plt.legend(
        loc='center left',
        bbox_to_anchor=(1.02, 0.5),
        fontsize=9
    )

    plt.grid()
    plt.axis('equal')

    # Guardar cada gráfica
    nombre = f"van_der_pol_mu_{str(mu).replace('.', '_')}.png"

    plt.savefig(nombre, dpi=300, bbox_inches='tight')
    plt.show()