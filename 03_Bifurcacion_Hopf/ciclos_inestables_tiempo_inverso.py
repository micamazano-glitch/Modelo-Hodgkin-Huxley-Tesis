import numpy as np
import matplotlib.pyplot as plt

from scipy.integrate import solve_ivp
from scipy.optimize import brentq


# ============================================================
# 1. PARÁMETROS DEL MODELO
# ============================================================

Cm = 1.0

gNa = 120.0
gK  = 36.0
gL  = 0.3

ENa = 50.0
EK  = -77.0
EL  = -54.387


# Punto de Hopf calculado previamente
IH = 6.752633193
VH = -60.810685829
nH = 0.383353023


# ============================================================
# 2. FUNCIONES DE HODGKEN-HUXLEY
# ============================================================

def alpha_m(V):

    z = (V + 40.0) / 10.0

    if abs(z) < 1e-8:
        return 1.0

    return 0.1*(V + 40.0)/(1.0 - np.exp(-z))


def beta_m(V):

    return 4.0*np.exp(-(V + 65.0)/18.0)


def alpha_n(V):

    z = (V + 55.0) / 10.0

    if abs(z) < 1e-8:
        return 0.1

    return 0.01*(V + 55.0)/(1.0 - np.exp(-z))


def beta_n(V):

    return 0.125*np.exp(-(V + 65.0)/80.0)


def m_inf(V):

    return alpha_m(V)/(alpha_m(V) + beta_m(V))


def n_inf(V):

    return alpha_n(V)/(alpha_n(V) + beta_n(V))


# ============================================================
# 3. SISTEMA REDUCIDO DE RINZEL
#
# h = 0.89 - 1.1 n
# m = m_inf(V)
# ============================================================

def sistema(t, Y, Iapp):

    V, n = Y

    m = m_inf(V)

    h = 0.89 - 1.1*n

    INa = gNa*m**3*h*(V - ENa)

    IK = gK*n**4*(V - EK)

    IL = gL*(V - EL)

    dVdt = (
        Iapp
        - INa
        - IK
        - IL
    )/Cm

    dndt = (
        alpha_n(V)*(1.0 - n)
        - beta_n(V)*n
    )

    return np.array([dVdt, dndt])


# ============================================================
# 4. SISTEMA CON TIEMPO INVERTIDO
#
# tau = -t
#
# dX/dtau = -F(X)
# ============================================================

def sistema_inverso(tau, Y, Iapp):

    return -sistema(tau, Y, Iapp)


# ============================================================
# 5. RAMA DE EQUILIBRIOS
#
# n* = n_inf(V*)
#
# Iext = I_equilibrio(V*)
# ============================================================

def I_equilibrio(V):

    n = n_inf(V)

    m = m_inf(V)

    h = 0.89 - 1.1*n

    INa = gNa*m**3*h*(V - ENa)

    IK = gK*n**4*(V - EK)

    IL = gL*(V - EL)

    return INa + IK + IL


# ============================================================
# 6. ENCONTRAR EQUILIBRIO PARA UNA CORRIENTE DADA
# ============================================================

def equilibrio(Iapp):

    fun = lambda V: I_equilibrio(V) - Iapp

    V_eq = brentq(
        fun,
        -70.0,
        -55.0
    )

    n_eq = n_inf(V_eq)

    return V_eq, n_eq


# ============================================================
# 7. CORRIENTES PARA CALCULAR LOS CICLOS
#
# Todas deben estar por debajo de IH.
#
# Colocamos más puntos cerca del Hopf.
# ============================================================

corrientes = np.array([

    6.70,
    6.72,
    6.74,
    6.745,
    6.750,
    6.751,
    6.752,
    6.7522,
    6.7524,
    6.7525

])


# ============================================================
# 8. LISTAS PARA GUARDAR RESULTADOS
# ============================================================

I_lista = []

Veq_lista = []
neq_lista = []

Vmax_lista = []
Vmin_lista = []

nmax_lista = []
nmin_lista = []

amplitud_lista = []

ciclos = []


# ============================================================
# 9. CALCULAR LOS CICLOS EN TIEMPO INVERSO
# ============================================================

for Iapp in corrientes:

    # --------------------------------------------------------
    # Equilibrio
    # --------------------------------------------------------

    Veq, neq = equilibrio(Iapp)


    # --------------------------------------------------------
    # Condición inicial
    #
    # Muy cerca del equilibrio.
    # En tiempo inverso el equilibrio es inestable.
    # --------------------------------------------------------

    Y0 = [
        Veq + 0.05,
        neq
    ]


    # --------------------------------------------------------
    # Integración en tiempo inverso
    # --------------------------------------------------------

    T = 6000.0

    sol = solve_ivp(

        lambda tau, Y:
            sistema_inverso(
                tau,
                Y,
                Iapp
            ),

        (0.0, T),

        Y0,

        method='DOP853',

        rtol=1e-10,
        atol=1e-12,

        max_step=0.1
    )


    V = sol.y[0]
    n = sol.y[1]


    # --------------------------------------------------------
    # Descartamos el transitorio
    #
    # Conservamos el último 20 %
    # --------------------------------------------------------

    inicio = int(0.80*len(V))

    Vc = V[inicio:]
    nc = n[inicio:]


    # --------------------------------------------------------
    # Extremos del ciclo
    # --------------------------------------------------------

    Vmax = np.max(Vc)
    Vmin = np.min(Vc)

    nmax = np.max(nc)
    nmin = np.min(nc)


    # --------------------------------------------------------
    # Amplitud en V
    # --------------------------------------------------------

    amplitud = (
        Vmax - Vmin
    )/2.0


    # --------------------------------------------------------
    # Guardar resultados
    # --------------------------------------------------------

    I_lista.append(Iapp)

    Veq_lista.append(Veq)
    neq_lista.append(neq)

    Vmax_lista.append(Vmax)
    Vmin_lista.append(Vmin)

    nmax_lista.append(nmax)
    nmin_lista.append(nmin)

    amplitud_lista.append(amplitud)

    # Se corrige de Iext a Iapp para evitar guardar un valor erróneo
    ciclos.append(
        (Iapp, Vc, nc, Veq, neq)
    )


    # --------------------------------------------------------
    # Información en pantalla
    # --------------------------------------------------------

    print(
        f"I = {Iapp:.7f}   "
        f"V* = {Veq:.7f}   "
        f"n* = {neq:.7f}   "
        f"Vmin = {Vmin:.7f}   "
        f"Vmax = {Vmax:.7f}   "
        f"A = {amplitud:.7f}"
    )


# Convertimos a arrays

I_lista = np.array(I_lista)

Veq_lista = np.array(Veq_lista)
neq_lista = np.array(neq_lista)

Vmax_lista = np.array(Vmax_lista)
Vmin_lista = np.array(Vmin_lista)

amplitud_lista = np.array(amplitud_lista)


# ============================================================
#
# FIGURA 1
