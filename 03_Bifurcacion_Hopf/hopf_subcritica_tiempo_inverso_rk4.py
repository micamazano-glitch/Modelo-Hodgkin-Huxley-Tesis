import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import brentq


# ============================================================
# 1. PARÁMETROS DEL MODELO
# ============================================================

Cm = 1.0

gNa = 120.0
gK = 36.0
gL = 0.3

ENa = 50.0
EK = -77.0
EL = -54.387

# Punto de Hopf calculado previamente
IH = 6.752633193
VH = -60.810685829
nH = 0.383353023


# ============================================================
# 2. FUNCIONES DE HODGKIN-HUXLEY
# ============================================================

def alpha_m(V):

    z = (V + 40.0) / 10.0

    if abs(z) < 1e-8:
        return 1.0

    return 0.1 * (V + 40.0) / (1.0 - np.exp(-z))


def beta_m(V):

    return 4.0 * np.exp(-(V + 65.0) / 18.0)


def alpha_n(V):

    z = (V + 55.0) / 10.0

    if abs(z) < 1e-8:
        return 0.1

    return 0.01 * (V + 55.0) / (1.0 - np.exp(-z))


def beta_n(V):

    return 0.125 * np.exp(-(V + 65.0) / 80.0)


def m_inf(V):

    return alpha_m(V) / (alpha_m(V) + beta_m(V))


def n_inf(V):

    return alpha_n(V) / (alpha_n(V) + beta_n(V))


# ============================================================
# 3. SISTEMA REDUCIDO DE HODGKIN-HUXLEY
#
# h = 0.89 - 1.1*n
# m = m_inf(V)
# ============================================================

def sistema(t, Y, Iapp):

    V, n = Y

    m = m_inf(V)
    h = 0.89 - 1.1 * n

    INa = gNa * m**3 * h * (V - ENa)
    IK = gK * n**4 * (V - EK)
    IL = gL * (V - EL)

    dVdt = (Iapp - INa - IK - IL) / Cm

    dndt = (
        alpha_n(V) * (1.0 - n)
        - beta_n(V) * n
    )

    return np.array([dVdt, dndt])


# ============================================================
# 4. SISTEMA CON TIEMPO INVERTIDO
#
# tau = -t
#
# dX/dtau = -F(X)
# ============================================================

def sistema_inverso(tau, Y, Iapp):

    return -sistema(tau, Y, Iapp)


# ============================================================
# 5. MÉTODO DE RUNGE-KUTTA DE CUARTO ORDEN
# ============================================================

def paso_RK4(f, t, Y, dt, Iapp):

    k1 = f(t, Y, Iapp)

    k2 = f(
        t + dt / 2.0,
        Y + (dt / 2.0) * k1,
        Iapp
    )

    k3 = f(
        t + dt / 2.0,
        Y + (dt / 2.0) * k2,
        Iapp
    )

    k4 = f(
        t + dt,
        Y + dt * k3,
        Iapp
    )

    return Y + (dt / 6.0) * (
        k1 + 2*k2 + 2*k3 + k4
    )


def integrar_RK4(f, Y0, T, dt, Iapp):

    N = int(round(T / dt))

    # Conservamos solamente el último 20 %
    inicio = int(0.80 * N)

    Vc = np.empty(N - inicio + 1)
    nc = np.empty(N - inicio + 1)

    Y = np.array(Y0, dtype=float)

    j = 0

    for i in range(N + 1):

        if i >= inicio:

            Vc[j] = Y[0]
            nc[j] = Y[1]

            j += 1

        if i == N:
            break

        Y = paso_RK4(
            f,
            i * dt,
            Y,
            dt,
            Iapp
        )

        if not np.all(np.isfinite(Y)):
            raise RuntimeError(
                f"La integración diverge para Iapp={Iapp}"
            )

    return Vc, nc


# ============================================================
# 6. RAMA DE EQUILIBRIOS
# ============================================================

def I_equilibrio(V):

    n = n_inf(V)
    m = m_inf(V)
    h = 0.89 - 1.1 * n

    INa = gNa * m**3 * h * (V - ENa)
    IK = gK * n**4 * (V - EK)
    IL = gL * (V - EL)

    return INa + IK + IL


# ============================================================
# 7. ENCONTRAR EQUILIBRIO PARA UNA CORRIENTE DADA
# ============================================================

def equilibrio(Iapp):

    fun = lambda V: I_equilibrio(V) - Iapp

    V_eq = brentq(
        fun,
        -70.0,
        -55.0
    )

    n_eq = n_inf(V_eq)

    return V_eq, n_eq


# ============================================================
# 8. CORRIENTES PARA CALCULAR LOS CICLOS
#
# Todas están por debajo de IH.
# ============================================================

corrientes = np.array([
    6.70,
    6.72,
    6.74,
    6.745,
    6.750,
    6.751,
    6.752,
    6.7522,
    6.7524,
    6.7525
])


# ============================================================
# 9. PARÁMETROS DE INTEGRACIÓN
# ============================================================

T = 6000.0       # ms
dt = 0.01        # ms

print("Integración en tiempo inverso mediante RK4")
print(f"Paso temporal: {dt} ms")
print(f"Tiempo total: {T} ms")
print()


# ============================================================
# 10. LISTAS PARA GUARDAR RESULTADOS
# ============================================================

I_lista = []

Veq_lista = []
neq_lista = []

Vmax_lista = []
Vmin_lista = []

nmax_lista = []
nmin_lista = []

amplitud_lista = []

ciclos = []


# ============================================================
# 11. CALCULAR LOS CICLOS EN TIEMPO INVERSO
# ============================================================

for Iapp in corrientes:

    # Equilibrio correspondiente
    Veq, neq = equilibrio(Iapp)

    # Condición inicial cercana al equilibrio
    Y0 = [
        Veq + 0.05,
        neq
    ]

    # Integración en tiempo inverso con RK4
    Vc, nc = integrar_RK4(
        sistema_inverso,
        Y0,
        T,
        dt,
        Iapp
    )

    # Extremos del ciclo
    Vmax = np.max(Vc)
    Vmin = np.min(Vc)

    nmax = np.max(nc)
    nmin = np.min(nc)

    # Semiamplitud en V
    amplitud = (Vmax - Vmin) / 2.0

    # Guardar resultados
    I_lista.append(Iapp)

    Veq_lista.append(Veq)
    neq_lista.append(neq)

    Vmax_lista.append(Vmax)
    Vmin_lista.append(Vmin)

    nmax_lista.append(nmax)
    nmin_lista.append(nmin)

    amplitud_lista.append(amplitud)

    ciclos.append(
        (Iapp, Vc, nc, Veq, neq)
    )

    print(
        f"I = {Iapp:.7f}   "
        f"V* = {Veq:.7f}   "
        f"n* = {neq:.7f}   "
        f"Vmin = {Vmin:.7f}   "
        f"Vmax = {Vmax:.7f}   "
        f"A = {amplitud:.7f}"
    )


# Convertir listas a arrays
