import numpy as np
from scipy.optimize import root

# Parametros del modelo reducido
Cm = 1.0
gNa = 120.0
gK = 36.0
gL = 0.3
ENa = 50.0
EK = -77.0
EL = -54.387

corrientes = [0.0, 6.75, 6.76, 12.0]
paso = 1e-5

# Funciones auxiliares
def vtrap(x, y):
    if abs(x / y) < 1e-6:
        return y * (1.0 - x / (2.0 * y))
    return x / np.expm1(x / y)

def vtrap_derivada(x, y):
    z = x / y
    if abs(z) < 1e-4:
        return -0.5 + z / 6.0 - z**3 / 180.0
    return (np.expm1(z) - z * np.exp(z)) / np.expm1(z)**2

def alpha_m(V):
    return 0.1 * vtrap(-(V + 40.0), 10.0)

def beta_m(V):
    return 4.0 * np.exp(-(V + 65.0) / 18.0)

def alpha_n(V):
    return 0.01 * vtrap(-(V + 55.0), 10.0)

def beta_n(V):
    return 0.125 * np.exp(-(V + 65.0) / 80.0)

def m_inf(V):
    a = alpha_m(V)
    b = beta_m(V)
    return a / (a + b)

def m_inf_derivada(V):
    a = alpha_m(V)
    b = beta_m(V)
    da = -0.1 * vtrap_derivada(-(V + 40.0), 10.0)
    db = -b / 18.0
    return (da * b - a * db) / (a + b)**2

def alpha_n_derivada(V):
    return -0.01 * vtrap_derivada(-(V + 55.0), 10.0)

def beta_n_derivada(V):
    return -beta_n(V) / 80.0

# Sistema reducido bidimensional
def modelo_reducido(y, Iapp):
    V, n = y
    m = m_inf(V)
    h = 0.89 - 1.1 * n

    dV = (
        gK * n**4 * (EK - V)
        + gNa * m**3 * h * (ENa - V)
        + gL * (EL - V)
        + Iapp
    ) / Cm

    dn = alpha_n(V) * (1.0 - n) - beta_n(V) * n
    return np.array([dV, dn])

# Jacobiano analitico
def jacobiano_analitico(y):
    V, n = y
    m = m_inf(V)
    dm = m_inf_derivada(V)
    h = 0.89 - 1.1 * n

    fV = (
        -gK * n**4 - gL
        + gNa * h * (
            3.0 * m**2 * dm * (ENa - V) - m**3
        )
    ) / Cm

    fn = (
        4.0 * gK * n**3 * (EK - V)
        - 1.1 * gNa * m**3 * (ENa - V)
    ) / Cm

    gV = (
        alpha_n_derivada(V) * (1.0 - n)
        - beta_n_derivada(V) * n
    )

    gn = -alpha_n(V) - beta_n(V)

    return np.array([[fV, fn], [gV, gn]])

# Jacobiano por diferencias finitas centradas
def jacobiano_numerico(y, Iapp, paso=1e-5):
    J = np.zeros((2, 2))

    for j in range(2):
        desplazamiento = np.zeros(2)
        desplazamiento[j] = paso

        J[:, j] = (
            modelo_reducido(y + desplazamiento, Iapp)
            - modelo_reducido(y - desplazamiento, Iapp)
        ) / (2.0 * paso)

    return J

# Calculo de la tabla
print(" I_app    Diferencia en J    Diferencia en lambda")
print("-" * 54)

for Iapp in corrientes:
    solucion = root(
        lambda y: modelo_reducido(y, Iapp),
        [-65.0, 0.32],
        tol=1e-12
    )

    if np.linalg.norm(solucion.fun, ord=np.inf) > 1e-9:
        raise RuntimeError(
            f"No se encontro el equilibrio para I={Iapp}"
        )

    equilibrio = solucion.x

    Ja = jacobiano_analitico(equilibrio)
    Jn = jacobiano_numerico(equilibrio, Iapp, paso)

    diferencia_J = np.max(np.abs(Ja - Jn))

    autovalores_a = np.linalg.eigvals(Ja)
    autovalores_n = np.linalg.eigvals(Jn)

    # Emparejar autovalores por distancia minima
    error_directo = np.max(
        np.abs(autovalores_a - autovalores_n)
    )
    error_invertido = np.max(
        np.abs(autovalores_a - autovalores_n[::-1])
    )
    diferencia_lambda = min(error_directo, error_invertido)

    print(
        f"{Iapp:6.2f}    "
        f"{diferencia_J:.3e}          "
        f"{diferencia_lambda:.3e}"
    )