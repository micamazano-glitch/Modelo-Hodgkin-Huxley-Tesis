import numpy as np
import matplotlib.pyplot as plt

# Definimos el sistema
def sistema(x, y):
    dx = x + y
    dy = 4*x - 2*y
    return dx, dy

# Malla de puntos
x_vals = np.linspace(-5, 5, 20)
y_vals = np.linspace(-5, 5, 20)
X, Y = np.meshgrid(x_vals, y_vals)

# Campo de direcciones
DX, DY = sistema(X, Y)

# Crear figura
plt.figure(figsize=(7, 5))

# Campo vectorial
plt.quiver(X, Y, DX, DY)

# Trayectorias (usando soluciones explícitas)
t = np.linspace(-2, 2, 200)

# Algunas condiciones iniciales
condiciones = [
    (1, 0), (0, 1), (2, -1), (-1, 2), (-2, -1)
]

for x0, y0 in condiciones:
    c1 = (4*x0 + y0)/5
    c2 = (x0 - y0)/5

    x = c1*np.exp(2*t) + c2*np.exp(-3*t)
    y = c1*np.exp(2*t) - 4*c2*np.exp(-3*t)

    plt.plot(x, y)

# Rectas propias (variedades)
s = np.linspace(-5, 5, 100)

# Variedad inestable (v1 = (1,1))
plt.plot(s, s, linestyle='--', label="Dirección de V_1")

# Variedad estable (v2 = (1,-4))
plt.plot(s, -4*s, linestyle='--', label="Direccion de V_2")

# Punto crítico
plt.scatter(0, 0)

# Ejes
plt.axhline(0, color='black')
plt.axvline(0, color='black')

# Escala igual
plt.axis('equal')


# Límites
plt.xlim(-5, 5)
plt.ylim(-5, 5)

# Título y leyenda
#plt.title()
plt.legend()
plt.grid()
plt.savefig("fase.png", dpi=300)
plt.show()