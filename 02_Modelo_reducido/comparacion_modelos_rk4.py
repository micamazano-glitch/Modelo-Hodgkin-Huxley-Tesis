import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import find_peaks

# ============================================================
# 1. PARAMETROS
# ============================================================

Cm = 1.0
gNa = 120.0
gK = 36.0
gL = 0.3

ENa = 50.0
EK = -77.0
EL = -54.387

corrientes = [6.75, 6.76, 12.0]

dt = 0.01
t_final = 100.0
t = np.arange(0.0, t_final + dt/2, dt)

# Para las mediciones descartamos el transitorio inicial
t_transitorio = 20.0

# ============================================================
# 2. FUNCIONES DE COMPUERTA
# ============================================================

def vtrap(x, y):
    if abs(x/y) < 1e-6:
        return y * (1.0 - x/(2.0*y))
    return x / np.expm1(x/y)

def alpha_m(V):
    return 0.1 * vtrap(-(V+40.0), 10.0)

def beta_m(V):
    return 4.0 * np.exp(-(V+65.0)/18.0)

def alpha_h(V):
    return 0.07 * np.exp(-(V+65.0)/20.0)

def beta_h(V):
    return 1.0/(1.0+np.exp(-(V+35.0)/10.0))

def alpha_n(V):
    return 0.01 * vtrap(-(V+55.0), 10.0)

def beta_n(V):
    return 0.125 * np.exp(-(V+65.0)/80.0)

def estacionario(alpha, beta, V):
    return alpha(V)/(alpha(V)+beta(V))

def m_inf(V):
    return estacionario(alpha_m, beta_m, V)

# ============================================================
# 3. MODELO COMPLETO
# ============================================================

def modelo_completo(y, Iapp):
    V, m, h, n = y

    INa = gNa*m**3*h*(V-ENa)
    IK = gK*n**4*(V-EK)
    IL = gL*(V-EL)

    dV = (Iapp-INa-IK-IL)/Cm
    dm = alpha_m(V)*(1-m)-beta_m(V)*m
    dh = alpha_h(V)*(1-h)-beta_h(V)*h
    dn = alpha_n(V)*(1-n)-beta_n(V)*n

    return np.array([dV, dm, dh, dn])

# ============================================================
# 4. MODELO REDUCIDO BIDIMENSIONAL
# ============================================================

def modelo_reducido(y, Iapp):
    V, n = y

    m = m_inf(V)
    h = 0.89-1.1*n

    INa = gNa*m**3*h*(V-ENa)
    IK = gK*n**4*(V-EK)
    IL = gL*(V-EL)

    dV = (Iapp-INa-IK-IL)/Cm
    dn = alpha_n(V)*(1-n)-beta_n(V)*n

    return np.array([dV, dn])

# ============================================================
# 5. RUNGE-KUTTA DE CUARTO ORDEN
# ============================================================

def rk4(f, y0, Iapp, t, dt):
    solucion = np.zeros((len(t), len(y0)))
    solucion[0] = y0

    for i in range(len(t)-1):
        y = solucion[i]

        k1 = f(y, Iapp)
        k2 = f(y+dt*k1/2, Iapp)
        k3 = f(y+dt*k2/2, Iapp)
        k4 = f(y+dt*k3, Iapp)

        solucion[i+1] = y + dt*(k1+2*k2+2*k3+k4)/6

    return solucion

# ============================================================
# 6. INDICADORES CUANTITATIVOS
# ============================================================

def cruce_lineal(t1, t2, v1, v2, nivel):
    return t1 + (nivel-v1)*(t2-t1)/(v2-v1)

def indicadores(t, V, inicio=20.0):

    # Maximos despues del transitorio
    picos, _ = find_peaks(
        V,
        height=0.0,
        prominence=30.0,
        distance=int(3.0/dt)
    )

    picos = picos[t[picos] >= inicio]

    if len(picos) < 2:
        return np.nan, np.nan, np.nan

    # Frecuencia media
    periodos = np.diff(t[picos])
    frecuencia = 1000.0/np.mean(periodos)

    amplitudes = []
    anchos = []

    # Ciclos completos entre picos consecutivos
    for k in range(len(picos)-1):

        p1 = picos[k]
        p2 = picos[k+1]

        # Minimo entre dos picos consecutivos
        minimo = p1 + np.argmin(V[p1:p2+1])

        amplitud = V[p1]-V[minimo]
        amplitudes.append(amplitud)

        nivel = V[minimo]+amplitud/2.0

        # Cruce descendente despues del primer pico
        descenso = None
        for j in range(p1, minimo):
            if V[j] >= nivel and V[j+1] < nivel:
                descenso = cruce_lineal(
                    t[j], t[j+1],
                    V[j], V[j+1], nivel
                )
                break

        # Cruce ascendente antes del siguiente pico
        ascenso = None
        for j in range(minimo, p2):
            if V[j] < nivel and V[j+1] >= nivel:
                ascenso = cruce_lineal(
                    t[j], t[j+1],
                    V[j], V[j+1], nivel
                )
                break

        # El ancho del pico siguiente necesita su descenso.
        # Se usa el mismo nivel para el ciclo considerado.
        # Para medir el ancho del primer pico, buscamos su
        # cruce ascendente antes de p1.
        ascenso_pico = None
        for j in range(p1-1, 0, -1):
            if V[j] < nivel and V[j+1] >= nivel:
                ascenso_pico = cruce_lineal(
                    t[j], t[j+1],
                    V[j], V[j+1], nivel
                )
                break

        if ascenso_pico is not None and descenso is not None:
            anchos.append(descenso-ascenso_pico)

    amplitud_media = np.mean(amplitudes)
    ancho_medio = np.mean(anchos) if anchos else np.nan

    return frecuencia, amplitud_media, ancho_medio

def error_relativo(completo, reducido):
    if not np.isfinite(completo) or not np.isfinite(reducido):
        return np.nan
    if completo == 0:
        return np.nan
    return 100.0*abs(reducido-completo)/abs(completo)

# ============================================================
# 7. CONDICIONES INICIALES
# ============================================================

V0 = -65.0

m0 = estacionario(alpha_m, beta_m, V0)
h0 = estacionario(alpha_h, beta_h, V0)
n0 = estacionario(alpha_n, beta_n, V0)

y0_completo = np.array([V0, m0, h0, n0])
y0_reducido = np.array([V0, n0])

# ============================================================
# 8. SIMULACIONES Y TABLA
# ============================================================

resultados = []

for Iapp in corrientes:

    sol_c = rk4(
        modelo_completo, y0_completo, Iapp, t, dt
    )

    sol_r = rk4(
        modelo_reducido, y0_reducido, Iapp, t, dt
    )

    Vc = sol_c[:, 0]
    Vr = sol_r[:, 0]

    fc, Ac, Wc = indicadores(t, Vc, t_transitorio)
    fr, Ar, Wr = indicadores(t, Vr, t_transitorio)

    ef = error_relativo(fc, fr)
    ea = error_relativo(Ac, Ar)
    ew = error_relativo(Wc, Wr)

    resultados.append([Iapp, ef, ea, ew])

    # ========================================================
    # 9. GRAFICAS COMPARATIVAS
    # ========================================================

    fig, ax = plt.subplots(
        2, 1, figsize=(9, 6)
    )

    ax[0].plot(
        t, Vc, "k-", linewidth=0.8,
        label="Modelo completo"
    )
    ax[0].plot(
        t, Vr, "r--", linewidth=0.8,
        label="Modelo reducido"
    )

    ax[0].set_title(
        f"Comparacion de modelos, Iapp = {Iapp:.2f}"
    )
    ax[0].set_ylabel("V (mV)")
    ax[0].legend()
    ax[0].grid(alpha=0.3)
    ax[0].set_xlim(0, 100)

    ax[1].plot(
        t, Vc, "k-", linewidth=1,
        label="Completo"
    )
    ax[1].plot(
        t, Vr, "r--", linewidth=1,
        label="Reducido"
    )

    ax[1].set_xlim(40, 80)
    ax[1].set_xlabel("t (ms)")
    ax[1].set_ylabel("V (mV)")
    ax[1].legend()
    ax[1].grid(alpha=0.3)

    plt.tight_layout()

    etiqueta = str(Iapp).replace(".", "_")

    plt.savefig(
        f"comparacion_modelos_I{etiqueta}.png",
        dpi=300,
        bbox_inches="tight"
    )

    plt.show()

# ============================================================
# 10. IMPRIMIR TABLA FINAL
# ============================================================

print("\nERRORES RELATIVOS DEL MODELO REDUCIDO")
print("="*65)
print(
    f"{'Iapp':>8} {'Frecuencia (%)':>17}"
    f"{'Amplitud (%)':>17} {'Ancho (%)':>15}"
)
print("-"*65)

for fila in resultados:
    Iapp, ef, ea, ew = fila
    print(
        f"{Iapp:8.2f} {ef:17.4f}"
        f"{ea:17.4f} {ew:15.4f}"
    )

np.savetxt(
    "errores_modelo_reducido_RK4.csv",
    np.array(resultados),
    delimiter=",",
    header="Iapp,error_frecuencia_pct,error_amplitud_pct,error_ancho_pct",
    comments=""
)

print("\nResultados guardados en CSV.")