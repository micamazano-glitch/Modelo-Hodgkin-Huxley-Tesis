import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import fsolve

# =====================================================
# Constantes del modelo (Valores típicos de Hodgkin-Huxley)
# =====================================================
C_m = 1.0     # Capacitancia de la membrana (uF/cm^2)
G_K = 36.0    # Conductancia máxima de potasio (mS/cm^2)
G_Na = 120.0  # Conductancia máxima de sodio (mS/cm^2)
G_L = 0.3     # Conductancia de fuga (mS/cm^2)
E_K = -77.0   # Potencial de equilibrio de potasio (mV)
E_Na = 50.0   # Potencial de equilibrio de sodio (mV)
E_L = -54.387   # Potencial de equilibrio de fuga (mV)

# =====================================================
# Funciones auxiliares
# =====================================================

def alpha_m(V):
    x = V + 40
    denom = 1 - np.exp(-0.1*x)
    # Use np.divide with out and where to handle division by zero safely
    term = np.divide(0.1*x, denom, out=np.full_like(x, np.inf, dtype=float), where=denom!=0)
    # Use np.where to apply the limit when x is near zero
    return np.where(np.isclose(x, 0, atol=1e-8), 1.0, term)

def beta_m(V):
    return 4*np.exp(-0.0556*(V + 65))

def m_inf(V):
    return alpha_m(V)/(alpha_m(V) + beta_m(V))

def alpha_n(V):
    x = V + 55
    denom = 1 - np.exp(-0.1*x)
    # Use np.divide with out and where to handle division by zero safely
    term = np.divide(0.01*x, denom, out=np.full_like(x, np.inf, dtype=float), where=denom!=0)
    # Use np.where to apply the limit when x is near zero
    return np.where(np.isclose(x, 0, atol=1e-8), 0.1, term)

def beta_n(V):
    return 0.125*np.exp(-0.0125*(V + 65))

def n_inf(V):
    return alpha_n(V)/(alpha_n(V) + beta_n(V))

def dVdt(V, n, I):
    # Ecuación diferencial del voltaje de membrana (Hodgkin-Huxley simplificado)
    return (G_K * n**4 * (E_K - V) + \
            G_Na * m_inf(V)**3 * (0.89 - 1.1*n) * (E_Na - V) + \
            G_L * (E_L - V) + I) / C_m

# =====================================================
# Corriente aplicada
# =====================================================

I = 6.75

# =====================================================
# Nulclina de n
# =====================================================

V = np.linspace(-90, 60, 500)

n_nullcline = n_inf(V)

# =====================================================
# Nulclina de V
# =====================================================

V_Vnull = np.linspace(-90, 60, 400)
n_Vnull = []

for v_val in V_Vnull:
    def f(n_val):
        return dVdt(v_val, n_val, I)

    try:
        # Usar n_inf(v_val) como suposición inicial para fsolve
        # Esto proporciona una mejor estimación inicial para n
        n_sol = fsolve(f, n_inf(v_val))[0]

        if 0 <= n_sol <= 1:
            n_Vnull.append(n_sol)
        else:
            n_Vnull.append(np.nan) # n debe estar entre 0 y 1

    except Exception:
        n_Vnull.append(np.nan)

n_Vnull = np.array(n_Vnull)

# =====================================================
# Punto de equilibrio
# =====================================================

Veq = -60.811974
neq = 0.383333

# =====================================================
# Figura
# =====================================================

plt.figure(figsize=(7,4))

plt.plot(V,
         n_nullcline,
         linewidth=3,color="red",
         label=r'Nulclina de $n$')

plt.plot(V_Vnull,
         n_Vnull,
         linewidth=3,color="blue",
         label=r'Nulclina de $V$')

plt.plot(Veq,
         neq,
         'o',
         markersize=10,color="black",
         label='Punto fijo')

plt.xlabel(r'$V$ (mV)', fontsize=14)
plt.ylabel(r'$n$', fontsize=14)

plt.xlim(-75, 50)
plt.ylim(0, 1)

#plt.title(
 #       "Intersección de las nulclinas n y V con Iapp = 0",
  #      fontsize=14
   # )

plt.grid(alpha=0.3)

plt.legend(
    fontsize=8,
    loc='center left',
    bbox_to_anchor=(1.02, 0.5)

)

plt.tight_layout()

plt.savefig("nulclinas_equilibrio_I0.pdf",
            bbox_inches="tight")

