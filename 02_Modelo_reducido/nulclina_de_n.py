import numpy as np
import matplotlib.pyplot as plt

# ==========================
# Funciones alpha_n y beta_n
# ==========================

def alpha_n(V):
    x = V + 55
    return np.where(
        np.abs(x) < 1e-8,
        0.1,
        0.01*x/(1-np.exp(-0.1*x))
    )

def beta_n(V):
    return 0.125*np.exp(-0.0125*(V+65))

def n_inf(V):
    return alpha_n(V)/(alpha_n(V)+beta_n(V))

# ==========================
# Gráfico
# ==========================

V = np.linspace(-90,60,1000)

plt.figure(figsize=(8,5))
plt.plot(V,n_inf(V),linewidth=3,color="red")

plt.xlabel(r"$V$ (mV)",fontsize=14)
plt.ylabel(r"$n$",fontsize=14)
plt.title(r"Nulclina de $n$ ($dn/dt=0$)",fontsize=14)
plt.grid(True)
plt.show()