import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp
from scipy.optimize import root

# =====================================================
# PARAMETROS
# =====================================================

Cm = 1.0

gNa = 120.0
ENa = 50.0

gK = 36.0
EK = -77.0

gL = 0.3
EL = -54.387

# Corriente externa
I = 0

# Condiciones iniciales
initial_conditions = [
    [-80, 0.10],
    [-90, 0.50],
    [-40, 0.90],
    [-30, 0.60],
    [10, 0.80]
]

# =====================================================
# FUNCIONES HH
# =====================================================

def alpha_m(V):
    x = V + 40
    return np.where(
        np.abs(x) < 1e-8,
        1.0,
        0.1 * x / (1 - np.exp(-0.1 * x))
    )

def beta_m(V):
    return 4 * np.exp(-(V + 65) / 18)

def alpha_n(V):
    x = V + 55
    return np.where(
        np.abs(x) < 1e-8,
        0.1,
        0.01 * x / (1 - np.exp(-0.1 * x))
    )

def beta_n(V):
    return 0.125 * np.exp(-(V + 65) / 80)

def m_inf(V):
    return alpha_m(V) / (alpha_m(V) + beta_m(V))

def n_inf(V):
    return alpha_n(V) / (alpha_n(V) + beta_n(V))

# =====================================================
# SISTEMA
# =====================================================

def dVdt(V, n, I):
    return (
        gK * n**4 * (EK - V)
        + gNa * m_inf(V)**3 * (0.89 - 1.1 * n) * (ENa - V)
        + gL * (EL - V)
        + I
    ) / Cm

def dndt(V, n):
    return alpha_n(V) * (1 - n) - beta_n(V) * n

def sistema(t, y):
    V, n = y
    return [dVdt(V, n, I), dndt(V, n)]

# =====================================================
# GRILLA PARA EL PLANO DE FASES
# =====================================================

V_vals = np.linspace(-100, 60, 500)
n_vals = np.linspace(0, 1, 500)

V, n = np.meshgrid(V_vals, n_vals)

DV = dVdt(V, n, I)
DN = dndt(V, n)

# =====================================================
# PUNTO DE EQUILIBRIO
# =====================================================

def ecuaciones_equilibrio(y):
    V, n = y
    return [dVdt(V, n, I), dndt(V, n)]

equilibrio = root(ecuaciones_equilibrio, [-60, 0.3])

if equilibrio.success:
    V_eq, n_eq = equilibrio.x
else:
    V_eq, n_eq = np.nan, np.nan

# =====================================================
# GRAFICO
# =====================================================

plt.figure(figsize=(9.5, 4.5))

# Nulclina de V: dV/dt = 0
plt.contour(V, n, DV, levels=[0], colors="blue", linewidths=2)
plt.plot([], [], color="blue", linewidth=3, label=r"Nulclina de $V$")

# Nulclina de n: dn/dt = 0
plt.contour(V, n, DN, levels=[0], colors="red", linewidths=2)
plt.plot([], [], color="red", linewidth=3, label=r"Nulclina de $n$")

# Punto de equilibrio
if equilibrio.success:
    plt.scatter(
        V_eq,
        n_eq,
        color="black",
        s=70,
        zorder=5,
        label=f"Punto fijo ({V_eq:.2f}, {n_eq:.3f})"
    )

# Trayectorias
t_span = (0, 500)
t_eval = np.linspace(t_span[0], t_span[1], 10000)

for y0 in initial_conditions:
    sol = solve_ivp(
        sistema,
        t_span,
        y0,
        t_eval=t_eval,
        rtol=1e-8,
        atol=1e-10
    )

    V_traj = sol.y[0]
    n_traj = sol.y[1]

    plt.plot(
        V_traj,
        n_traj,
        linewidth=2,
        alpha=0.85,
        label=f"CI: V={y0[0]}, n={y0[1]}"
    )


    # Marcar condicion inicial
    plt.scatter(
        y0[0],
        y0[1],
        color="green",
        s=35,
        zorder=5
    )

# =====================================================
# CICLO LIMITE
# =====================================================
# Si hay oscilacion sostenida, la parte final de una trayectoria
# se aproxima al ciclo limite. Se usa la ultima condicion inicial.

sol_lc = solve_ivp(
    sistema,
    (0, 1500),
    initial_conditions[-1],
    t_eval=np.linspace(0, 1500, 30000),
    rtol=1e-8,
    atol=1e-10
)

V_lc = sol_lc.y[0]
n_lc = sol_lc.y[1]
t_lc = sol_lc.t

# Tomamos solo el tramo final
mask_final = t_lc > 1000
V_final = V_lc[mask_final]
n_final = n_lc[mask_final]

# Criterio simple: si en el tramo final hay amplitud apreciable,
# se dibuja como posible ciclo limite.
amp_V = np.max(V_final) - np.min(V_final)

if amp_V > 5:
    plt.plot(
        V_final,
        n_final,
        color="purple",
        linewidth=2.5,
        label="Ciclo limite"
    )


# =====================================================
# DETALLES DEL GRAFICO
# =====================================================

plt.xlabel("V [mV]", fontsize=14)
plt.ylabel("n", fontsize=15)
plt.title(
    f"Modelo Hodgkin-Huxley reducido con Iapp = {I}",
    fontsize=15
)
plt.xlim(-100, 60)
plt.ylim(0, 1)
plt.grid(True)

# Leyenda fuera de la gráfica
plt.legend(
    fontsize=9,
    loc="center left",
    bbox_to_anchor=(1.02, 0.5),
    borderaxespad=0
)

plt.tight_layout()
