import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp
from scipy.optimize import root
from scipy.signal import find_peaks

# =====================================================
# PARÁMETROS
# =====================================================

Cm = 1.0

gNa = 120.0
ENa = 50.0

gK = 36.0
EK = -77.0

gL = 0.3
EL = -54.387

# Corriente externa
I = 6.75

# Condiciones iniciales
initial_conditions = [
    [-80, 0.10],
    [-90, 0.50],
    [-40, 0.90],
    [-30, 0.60],
    [10, 0.80],
]


# =====================================================
# FUNCIONES HH
# =====================================================

def alpha_m(V):
    x = V + 40
    return np.where(
        np.abs(x) < 1e-8,
        1.0,
        0.1 * x / (1 - np.exp(-0.1 * x)),
    )


def beta_m(V):
    return 4 * np.exp(-(V + 65) / 18)


def alpha_n(V):
    x = V + 55
    return np.where(
        np.abs(x) < 1e-8,
        0.1,
        0.01 * x / (1 - np.exp(-0.1 * x)),
    )


def beta_n(V):
    return 0.125 * np.exp(-(V + 65) / 80)


def m_inf(V):
    return alpha_m(V) / (alpha_m(V) + beta_m(V))


def n_inf(V):
    return alpha_n(V) / (alpha_n(V) + beta_n(V))


# =====================================================
# SISTEMA
# =====================================================

def dVdt(V, n, corriente):
    return (
        gK * n**4 * (EK - V)
        + gNa * m_inf(V)**3 * (0.89 - 1.1 * n) * (ENa - V)
        + gL * (EL - V)
        + corriente
    ) / Cm


def dndt(V, n):
    return alpha_n(V) * (1 - n) - beta_n(V) * n


def sistema(t, y):
    V, n = y
    return [dVdt(V, n, I), dndt(V, n)]


# =====================================================
# GRILLA PARA EL PLANO DE FASES
# =====================================================

V_vals = np.linspace(-100, 60, 500)
n_vals = np.linspace(0, 1, 500)

V, n = np.meshgrid(V_vals, n_vals)

DV = dVdt(V, n, I)
DN = dndt(V, n)


# =====================================================
# PUNTO DE EQUILIBRIO, JACOBIANO Y VALORES PROPIOS
# =====================================================

def ecuaciones_equilibrio(y):
    V_eq, n_eq = y
    return [dVdt(V_eq, n_eq, I), dndt(V_eq, n_eq)]


def jacobiano_numerico(V_eq, n_eq, corriente, h=1e-5):
    def campo(y):
        V_aux, n_aux = y
        return np.array([
            dVdt(V_aux, n_aux, corriente),
            dndt(V_aux, n_aux),
        ])

    y_eq = np.array([V_eq, n_eq], dtype=float)
    J = np.zeros((2, 2))

    J[:, 0] = (
        campo(y_eq + np.array([h, 0.0]))
        - campo(y_eq - np.array([h, 0.0]))
    ) / (2 * h)

    J[:, 1] = (
        campo(y_eq + np.array([0.0, h]))
        - campo(y_eq - np.array([0.0, h]))
    ) / (2 * h)

    return J


equilibrio = root(ecuaciones_equilibrio, [-60, 0.3])

if equilibrio.success:
    V_eq, n_eq = equilibrio.x

    J = jacobiano_numerico(V_eq, n_eq, I)
    valores_propios = np.linalg.eigvals(J)
    maxima_parte_real = np.max(np.real(valores_propios))

    # El equilibrio pierde estabilidad cuando algún valor propio
    # tiene parte real positiva.
    equilibrio_inestable = maxima_parte_real > 0

    print(f"Corriente aplicada: I = {I}")
    print(f"Equilibrio: V* = {V_eq:.8f}, n* = {n_eq:.8f}")
    print("Jacobiano:")
    print(J)
    print("Valores propios:", valores_propios)
    print(f"Máxima parte real: {maxima_parte_real:.10f}")
    print("Equilibrio inestable:", equilibrio_inestable)
else:
    V_eq, n_eq = np.nan, np.nan
    valores_propios = np.array([np.nan, np.nan])
    maxima_parte_real = np.nan
    equilibrio_inestable = False
    print("No se pudo calcular el punto de equilibrio.")


# =====================================================
# GRÁFICO
# =====================================================

plt.figure(figsize=(9.5, 4.5))

# Nulclina de V: dV/dt = 0
plt.contour(V, n, DV, levels=[0], colors="blue", linewidths=2)
plt.plot([], [], color="blue", linewidth=3, label=r"Nulclina de $V$")

# Nulclina de n: dn/dt = 0
plt.contour(V, n, DN, levels=[0], colors="red", linewidths=2)
plt.plot([], [], color="red", linewidth=3, label=r"Nulclina de $n$")

# Punto de equilibrio
if equilibrio.success:
    plt.scatter(
        V_eq,
        n_eq,
        color="black",
        s=70,
        zorder=5,
        label=f"Punto fijo ({V_eq:.2f}, {n_eq:.3f})",
    )

# Trayectorias
t_span = (0, 500)
t_eval = np.linspace(t_span[0], t_span[1], 10000)

for y0 in initial_conditions:
    sol = solve_ivp(
        sistema,
        t_span,
        y0,
        t_eval=t_eval,
        rtol=1e-8,
        atol=1e-10,
    )

    V_traj = sol.y[0]
    n_traj = sol.y[1]

    plt.plot(
        V_traj,
        n_traj,
        linewidth=2,
        alpha=0.85,
        label=f"CI: V={y0[0]}, n={y0[1]}",
    )

    # Marcar condición inicial
    plt.scatter(
        y0[0],
        y0[1],
        color="green",
        s=35,
        zorder=5,
    )


# =====================================================
# DETECCIÓN DE CICLO LÍMITE
# =====================================================

sol_lc = solve_ivp(
    sistema,
    (0, 5000),
    initial_conditions[-1],
    t_eval=np.linspace(0, 5000, 50000),
    rtol=1e-9,
    atol=1e-11,
)

V_lc = sol_lc.y[0]
n_lc = sol_lc.y[1]
t_lc = sol_lc.t

# Se descarta el 80 % inicial para reducir el efecto del transitorio.
mask_final = t_lc > 4000
V_final = V_lc[mask_final]
n_final = n_lc[mask_final]

# Se comprueba si las últimas oscilaciones tienen amplitud constante.
picos, _ = find_peaks(V_final, prominence=1)
valles, _ = find_peaks(-V_final, prominence=1)

oscilacion_periodica = False

if len(picos) >= 5 and len(valles) >= 5:
    maximos = V_final[picos[-5:]]
    minimos = V_final[valles[-5:]]
    amplitudes = maximos - minimos

    amplitud_media = np.mean(amplitudes)
    variacion_relativa = np.std(amplitudes) / amplitud_media

    if amplitud_media > 5 and variacion_relativa < 0.02:
        oscilacion_periodica = True

# Se dibuja como ciclo límite únicamente si:
# 1) el equilibrio es inestable, y
# 2) la simulación presenta una oscilación periódica sostenida.
hay_ciclo_limite = equilibrio_inestable and oscilacion_periodica

print("Oscilación periódica detectada:", oscilacion_periodica)
print("Ciclo límite detectado:", hay_ciclo_limite)

if hay_ciclo_limite:
    plt.plot(
        V_final,
        n_final,
        color="purple",
        linewidth=2.5,
        label="Ciclo límite",
    )
else:
    print("No se detectó un ciclo límite estable.")


# =====================================================
# DETALLES DEL GRÁFICO
# =====================================================

plt.xlabel("V [mV]", fontsize=14)
plt.ylabel("n", fontsize=15)
plt.title(
    f"Modelo Hodgkin-Huxley reducido con Iapp = {I}",
    fontsize=15,
)
plt.xlim(-100, 60)
plt.ylim(0, 1)
plt.grid(True)

# Leyenda fuera de la gráfica
plt.legend(
    fontsize=9,
    loc="center left",
    bbox_to_anchor=(1.02, 0.5),
    borderaxespad=0,
)

plt.tight_layout()
plt.savefig(
    f"caso-Iapp-{I}.png",
    dpi=300,
    bbox_inches="tight",
)
plt.show()