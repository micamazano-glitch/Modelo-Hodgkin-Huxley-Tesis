import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import root, brentq

# ============================================================
# 1. DATOS DE LA SIMULACIÓN
# ============================================================

Iapp = 6.0  # Corriente aplicada (microA/cm²)

V0 = -60.81  # Voltaje inicial (mV)
n0 = 0.38    # Variable n inicial

t_final = 800.0  # Tiempo final (ms)
h = 0.01         # Paso temporal fijo (ms)

# Si se desea iniciar cerca del equilibrio
usar_condicion_cercana = False

delta_V = 0.002
delta_n = 0.0

# ============================================================
# 2. PARÁMETROS DEL MODELO
# ============================================================

Cm = 1.0

gK = 36.0
gNa = 120.0
gL = 0.3

EK = -77.0
ENa = 50.0
EL = -54.387

# ============================================================
# 3. FUNCIONES DE TRANSICIÓN
# ============================================================

def alpha_m(V):
    x = np.asarray(V, dtype=float) + 40.0

    with np.errstate(
        divide="ignore",
        invalid="ignore",
        over="ignore"
    ):
        resultado = 0.1*x / (-np.expm1(-x/10.0))

    return np.where(
        np.abs(x) < 1e-8,
        1.0,
        resultado
    )


def beta_m(V):
    return 4.0*np.exp(-(np.asarray(V)+65.0)/18.0)


def m_inf(V):
    am = alpha_m(V)
    bm = beta_m(V)
    return am/(am+bm)


def alpha_n(V):
    x = np.asarray(V, dtype=float) + 55.0

    with np.errstate(
        divide="ignore",
        invalid="ignore",
        over="ignore"
    ):
        resultado = 0.01*x / (-np.expm1(-x/10.0))

    return np.where(
        np.abs(x) < 1e-8,
        0.1,
        resultado
    )


def beta_n(V):
    return 0.125*np.exp(-(np.asarray(V)+65.0)/80.0)


def n_inf(V):
    an = alpha_n(V)
    bn = beta_n(V)
    return an/(an+bn)


# ============================================================
# 4. SISTEMA REDUCIDO DE HODGKIN--HUXLEY
# ============================================================

def dV_dt(V, n):

    h_compuerta = 0.89 - 1.1*n
    m = m_inf(V)

    corriente_K = gK*n**4*(EK-V)

    corriente_Na = (
        gNa*m**3*h_compuerta*(ENa-V)
    )

    corriente_L = gL*(EL-V)

    return (
        corriente_K
        + corriente_Na
        + corriente_L
        + Iapp
    ) / Cm


def dn_dt(V, n):

    return (
        alpha_n(V)*(1.0-n)
        - beta_n(V)*n
    )


def sistema(t, X):

    V, n = X

    return np.array([
        float(dV_dt(V, n)),
        float(dn_dt(V, n))
    ])


# ============================================================
# 5. CÁLCULO DEL PUNTO DE EQUILIBRIO
# ============================================================

def funcion_equilibrio(V):
    return float(dV_dt(V, n_inf(V)))


V_busqueda = np.linspace(-100, 60, 3000)

F_busqueda = np.array([
    funcion_equilibrio(V)
    for V in V_busqueda
])

raices = []

for i in range(len(V_busqueda)-1):

    if F_busqueda[i]*F_busqueda[i+1] < 0:

        raiz = brentq(
            funcion_equilibrio,
            V_busqueda[i],
            V_busqueda[i+1],
            xtol=1e-12
        )

        if not any(
            abs(raiz-r) < 1e-6
            for r in raices
        ):
            raices.append(raiz)


if len(raices) == 0:
    raise RuntimeError(
        "No se encontró un punto de equilibrio."
    )


V_eq = min(
    raices,
    key=lambda V: abs(V+60)
)

n_eq = float(n_inf(V_eq))

print("="*55)
print(f"Corriente aplicada: Iapp = {Iapp}")
print(f"Equilibrio: V* = {V_eq:.9f} mV")
print(f"Equilibrio: n* = {n_eq:.9f}")

# ============================================================
# 6. CONDICIÓN INICIAL
# ============================================================

if usar_condicion_cercana:

    V0 = V_eq + delta_V
    n0 = n_eq + delta_n

print(f"Condición inicial: ({V0}, {n0})")

# ============================================================
# 7. MÉTODO DE RUNGE--KUTTA DE CUARTO ORDEN
# ============================================================

def rk4(f, t0, X0, h, N):

    tiempos = np.empty(N+1)

    soluciones = np.empty(
        (N+1, len(X0))
    )

    t = t0
    X = np.array(X0, dtype=float)

    tiempos[0] = t
    soluciones[0] = X

    for i in range(N):

        k1 = f(t, X)

        k2 = f(
            t+h/2,
            X+h*k1/2
        )

        k3 = f(
            t+h/2,
            X+h*k2/2
        )

        k4 = f(
            t+h,
            X+h*k3
        )

        X = X + (h/6)*(
            k1 + 2*k2 + 2*k3 + k4
        )

        t = t0 + (i+1)*h

        tiempos[i+1] = t
        soluciones[i+1] = X

        if not np.all(np.isfinite(X)):
            raise RuntimeError(
                "La integración RK4 produjo "
                "valores no finitos."
            )

    return tiempos, soluciones


# ============================================================
# 8. INTEGRACIÓN NUMÉRICA CON RK4
# ============================================================

N = int(round(t_final/h))

t, soluciones = rk4(
    sistema,
    0.0,
    [V0, n0],
    h,
    N
)

V_t = soluciones[:, 0]
n_t = soluciones[:, 1]

print(f"Paso temporal: {h} ms")
print(f"Número de pasos: {N}")
print("Método utilizado: RK4 clásico")

# ============================================================
# 9. CÁLCULO DE LAS NULCLINAS
# ============================================================

def calcular_nulclina_V(V_array, n_referencia):

    valores = np.full(
        len(V_array),
        np.nan
    )

    semilla = n_referencia

    for i, V in enumerate(V_array):

        solucion_raiz = root(
            lambda X: [
                float(dV_dt(V, X[0]))
            ],
            [semilla],
            tol=1e-11
        )

        n_raiz = solucion_raiz.x[0]

        if (
            0 <= n_raiz <= 1
            and abs(dV_dt(V, n_raiz)) < 1e-7
        ):
            valores[i] = n_raiz
            semilla = n_raiz

    return valores


V_completo = np.linspace(
    -90, 50, 3000
)

V_izq = np.linspace(
    V_eq, -90, 1500
)

V_der = np.linspace(
    V_eq, 50, 1500
)

n_izq = calcular_nulclina_V(
    V_izq, n_eq
)

n_der = calcular_nulclina_V(
    V_der, n_eq
)

V_nulclina = np.concatenate([
    V_izq[::-1],
    V_der[1:]
])

n_nulclina_V = np.concatenate([
    n_izq[::-1],
    n_der[1:]
])

n_nulclina_n = n_inf(V_completo)

# ============================================================
# 10. FUNCIÓN PARA DIBUJAR EL PLANO DE FASE
