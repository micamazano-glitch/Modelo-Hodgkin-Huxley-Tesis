import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import fsolve

# ===================================
# Parámetros Hodgkin-Huxley reducidos
# ===================================

Cm = 1.0

gK = 36.0
gNa = 120.0
gL = 0.3

EK = -77.0
ENa = 50.0
EL = -54.387

Iapp = 0

# ===================================
# Funciones
# ===================================

def alpha_m(V):
    x = V + 40
    return np.where(
        np.abs(x) < 1e-8,
        1.0,
        0.1*x/(1-np.exp(-0.1*x))
    )

def beta_m(V):
    return 4*np.exp(-0.0556*(V+65))

def m_inf(V):
    am = alpha_m(V)
    bm = beta_m(V)
    return am/(am+bm)

# ===================================
# Función dV/dt
# ===================================

def F(V,n):

    return (
        gK*n**4*(EK-V)
        + gNa*m_inf(V)**3*(0.89-1.1*n)*(ENa-V)
        + gL*(EL-V)
        + Iapp
    )

# ===================================
# Buscar nulclina
# ===================================

Vvals = np.linspace(-75,50,300)

n_null = []

for V in Vvals:

    try:
        sol = fsolve(lambda n: F(V,n),0.3)[0]

        if 0 <= sol <= 1:
            n_null.append(sol)
        else:
            n_null.append(np.nan)

    except:
        n_null.append(np.nan)

# ===================================
# Gráfico
# ===================================

plt.figure(figsize=(8,5))

plt.plot(
    Vvals,
    n_null,
    linewidth=3
)

plt.xlabel(r"$V$ (mV)",fontsize=14)
plt.ylabel(r"$n$",fontsize=14)
plt.title(r"Nulclina de $V$ ($dV/dt=0$)",fontsize=14)
plt.grid(True)

plt.show()